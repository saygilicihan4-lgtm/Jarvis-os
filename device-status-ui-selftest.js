'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('public/mobile-reference-v195.js','utf8');
const start=source.indexOf('function deviceRepairHints('),end=source.indexOf('function diagnostics(){',start);
assert(start>0&&end>start,'pure device diagnostic mapper exists');
const context=vm.createContext({});
vm.runInContext(source.slice(start,end),context);
const hints=(devices,tr=true)=>Array.from(context.deviceRepairHints(devices,tr));
assert.deepEqual(hints(null),[],'older or missing server data remains unknown');
assert.match(hints({})[0],/kayıtlı PC cihazı görünmüyor/);
assert.deepEqual(hints({pc:{approved:true,online:true}}),[],'healthy device has no repair prompt');
const denied=hints({pc:{approved:false,online:false}});
assert.equal(denied.length,1);assert.match(denied[0],/kayıtlı cihaz onaysız/);
assert.match(denied[0],/sessizce yeniden onaylamıyoruz/);
const offline=hints({pc:{approved:true,online:false}},false);
assert.equal(offline.length,1);assert.match(offline[0],/approved device.*offline/);
assert.equal(hints({a:{approved:false,online:false},b:{approved:true,online:false}}).length,2);
assert(source.includes('if(fresh&&!pc?.online)lines.push(...deviceRepairHints('),'only a fresh offline state is diagnosed');
assert(!source.slice(start,end).includes('fetch('),'diagnostic mapper is read-only');
console.log('DEVICE STATUS UI PASS: missing, unapproved, approved offline, healthy and stale states');
